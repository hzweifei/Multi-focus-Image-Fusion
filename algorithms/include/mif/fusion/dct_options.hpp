#pragma once

namespace mif {

/// DCT 块方差融合参数：以空间域方差衡量块的全部交流能量，不显式融合 DCT 系数。
/// 各非重叠块选取清晰来源，再对来源索引做两次中值一致性处理。
struct DctOptions {
    /// 方形块边长，[2, 128]，单位为输入像素；不足整块的右侧/下侧边缘仍参与计算。
    int block_size = 8;
    /// 块级索引中值窗口边长，[1, 31] 内的奇数；1 表示不平滑来源选择。
    /// 该窗口以块为单位，默认 7 对应最多 7×7 个相邻块。
    int consistency_window = 7;
};

} // 命名空间 mif
